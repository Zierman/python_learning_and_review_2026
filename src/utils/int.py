def is_odd(i: int) -> bool:
    """Return True if the given integer is odd.

    Args:
        i: Integer to check.

    Returns:
        True if i is odd, otherwise False.
    """

    return i % 2 != 0


def is_negative(i: int) -> bool:
    """Return True if the given integer is negative.

    Args:
        i: Integer to check.

    Returns:
        True if i is negative, otherwise False.
    """

    return i < 0
